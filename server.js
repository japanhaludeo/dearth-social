'use strict';

const path = require('node:path');
const crypto = require('node:crypto');
const express = require('express');
const session = require('express-session');
const PgSession = require('connect-pg-simple')(session);
const bcrypt = require('bcryptjs');
const { Pool } = require('pg');

const app = express();
const PORT = Number(process.env.PORT) || 3000;

if (!process.env.DATABASE_URL) {
  throw new Error('DATABASE_URL environment variable is required.');
}
if (!process.env.SESSION_SECRET && process.env.NODE_ENV === 'production') {
  throw new Error('SESSION_SECRET environment variable is required in production.');
}

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  // Hosted PostgreSQL providers generally require TLS. Set PGSSL=false only for
  // trusted local development databases.
  ssl: process.env.PGSSL === 'false' ? false : { rejectUnauthorized: false },
  max: 5,
  idleTimeoutMillis: 10_000,
  connectionTimeoutMillis: 10_000
});

let schemaReady;
function initializeDatabase() {
  if (!schemaReady) {
    schemaReady = pool.query(`
      CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        account_id TEXT NOT NULL UNIQUE,
        account_name TEXT NOT NULL,
        password_hash TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
        updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE TABLE IF NOT EXISTS posts (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        body TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS posts_created_at_idx ON posts(created_at DESC, id DESC);
      CREATE TABLE IF NOT EXISTS replies (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
        user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
        body TEXT NOT NULL,
        created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
      );
      CREATE INDEX IF NOT EXISTS replies_post_id_idx ON replies(post_id, created_at, id);
      CREATE TABLE IF NOT EXISTS "session" (
        sid VARCHAR NOT NULL PRIMARY KEY,
        sess JSON NOT NULL,
        expire TIMESTAMP(6) NOT NULL
      );
      CREATE INDEX IF NOT EXISTS "IDX_session_expire" ON "session" (expire);
    `).catch(error => {
      schemaReady = null;
      throw error;
    });
  }
  return schemaReady;
}

app.disable('x-powered-by');
app.set('trust proxy', 1);
app.use(express.json({ limit: '16kb' }));
app.use(express.static(path.join(__dirname, 'public'), { extensions: ['html'] }));

// Netlify functions are stateless between invocations, so sessions must live in
// PostgreSQL rather than express-session's in-memory default store.
app.use(async (req, res, next) => {
  try {
    await initializeDatabase();
    next();
  } catch (error) {
    console.error('Database initialization failed:', error);
    res.status(503).json({ error: 'データベースに接続できません。設定を確認してください。' });
  }
});

app.use(session({
  name: 'dearthsocial.sid',
  secret: process.env.SESSION_SECRET || crypto.randomBytes(32).toString('hex'),
  store: new PgSession({ pool, tableName: 'session', createTableIfMissing: false }),
  resave: false,
  saveUninitialized: false,
  cookie: {
    httpOnly: true,
    sameSite: 'strict',
    secure: process.env.NODE_ENV === 'production' || Boolean(process.env.NETLIFY),
    maxAge: 1000 * 60 * 60 * 24 * 7
  }
}));

// Lightweight protection for demos. Use a distributed rate limiter for production.
const requestLog = new Map();
function rateLimit(req, res, next) {
  if (!req.path.startsWith('/api/')) return next();
  if (req.method === 'GET') return next();
  const key = `${req.ip}:${req.path}`;
  const now = Date.now();
  const entries = (requestLog.get(key) || []).filter(time => now - time < 60_000);
  entries.push(now);
  requestLog.set(key, entries);
  if (entries.length > 20) return res.status(429).json({ error: 'リクエストが多すぎます。しばらくしてからお試しください。' });
  next();
}
app.use(rateLimit);

function isSafeOrigin(req) {
  if (req.method === 'GET' || req.method === 'HEAD') return true;
  const origin = req.get('origin');
  if (!origin) return true;
  try {
    return req.get('host') === new URL(origin).host;
  } catch {
    return false;
  }
}

app.use((req, res, next) => {
  if (!isSafeOrigin(req)) return res.status(403).json({ error: '不正なリクエスト元です。' });
  if (['POST', 'PUT', 'PATCH', 'DELETE'].includes(req.method) && req.session.csrfToken && req.get('x-csrf-token') !== req.session.csrfToken) {
    return res.status(403).json({ error: 'セッションを確認できませんでした。ページを再読み込みしてください。' });
  }
  next();
});

function publicUser(row) {
  if (!row) return null;
  return { id: Number(row.id), accountId: row.account_id.toLowerCase(), accountName: row.account_name, createdAt: row.created_at };
}

function normalizeAccountId(value) {
  return String(value || '').trim().toLowerCase();
}

function validateRegistration(accountId, accountName, password) {
  if (!/^[a-z0-9_]{2,30}$/.test(accountId)) return 'アカウントIDは英数字・_を使い、2～30文字で入力してください。ハイフンは使えません。';
  if (!accountName || accountName.length > 50) return 'アカウント名は1～50文字で入力してください。';
  if (password.length < 2 || password.length > 72) return 'パスワードは2～72文字で入力してください。';
  return null;
}

function weightedLength(text) {
  const segmenter = new Intl.Segmenter('ja', { granularity: 'grapheme' });
  let length = 0;
  for (const { segment } of segmenter.segment(text)) {
    const codePoint = segment.codePointAt(0);
    length += codePoint <= 0x7f || (codePoint >= 0xff61 && codePoint <= 0xff9f) ? 1 : 2;
  }
  return length;
}

function validateText(text, maxLength, label) {
  if (!text.trim()) return `${label}を入力してください。`;
  if (weightedLength(text) > maxLength) return `${label}は全角2・半角1文字換算で${maxLength}文字以内にしてください。`;
  return null;
}

async function getSessionUser(req) {
  if (!req.session.userId) return null;
  const { rows } = await pool.query('SELECT * FROM users WHERE id = $1', [req.session.userId]);
  return rows[0] || null;
}

async function requireUser(req, res) {
  const user = await getSessionUser(req);
  if (!user) res.status(401).json({ error: 'ログインが必要です。' });
  return user;
}

async function getFeed() {
  const { rows: posts } = await pool.query(`
    SELECT p.id, p.user_id AS "userId", p.body, p.created_at AS "createdAt",
           u.account_id AS "accountId", u.account_name AS "accountName"
    FROM posts p JOIN users u ON u.id = p.user_id
    ORDER BY p.created_at DESC, p.id DESC
    LIMIT 50
  `);
  if (!posts.length) return [];
  const ids = posts.map(post => post.id);
  const { rows: replies } = await pool.query(`
    SELECT r.id, r.post_id AS "postId", r.user_id AS "userId", r.body,
           r.created_at AS "createdAt", u.account_id AS "accountId", u.account_name AS "accountName"
    FROM replies r JOIN users u ON u.id = r.user_id
    WHERE r.post_id = ANY($1::bigint[])
    ORDER BY r.created_at ASC, r.id ASC
  `, [ids]);
  const repliesByPost = new Map(ids.map(id => [String(id), []]));
  for (const reply of replies) {
    const list = repliesByPost.get(String(reply.postId));
    if (list.length < 100) list.push({
      id: Number(reply.id), userId: Number(reply.userId), body: reply.body,
      createdAt: reply.createdAt, accountId: reply.accountId.toLowerCase(), accountName: reply.accountName
    });
  }
  return posts.map(post => ({
    id: Number(post.id), userId: Number(post.userId), body: post.body,
    createdAt: post.createdAt, accountId: post.accountId.toLowerCase(),
    accountName: post.accountName, replies: repliesByPost.get(String(post.id))
  }));
}

function asyncRoute(handler) {
  return (req, res, next) => Promise.resolve(handler(req, res, next)).catch(next);
}

app.get('/api/csrf', (req, res) => {
  if (!req.session.csrfToken) req.session.csrfToken = crypto.randomBytes(32).toString('hex');
  res.json({ csrfToken: req.session.csrfToken });
});

app.get('/api/account', asyncRoute(async (req, res) => {
  res.json({ user: publicUser(await getSessionUser(req)) });
}));

app.get('/api/posts', asyncRoute(async (req, res) => {
  res.json({ posts: await getFeed() });
}));

app.post('/api/posts', asyncRoute(async (req, res) => {
  const user = await requireUser(req, res);
  if (!user) return;
  const body = String(req.body.body || '');
  const error = validateText(body, 256, '投稿');
  if (error) return res.status(400).json({ error });
  const { rows } = await pool.query('INSERT INTO posts (user_id, body) VALUES ($1, $2) RETURNING id', [user.id, body]);
  res.status(201).json({ postId: Number(rows[0].id), posts: await getFeed() });
}));

app.post('/api/posts/:postId/replies', asyncRoute(async (req, res) => {
  const user = await requireUser(req, res);
  if (!user) return;
  const postId = req.params.postId;
  if (!/^\d+$/.test(postId)) return res.status(404).json({ error: '投稿が見つかりません。' });
  const { rowCount } = await pool.query('SELECT 1 FROM posts WHERE id = $1', [postId]);
  if (!rowCount) return res.status(404).json({ error: '投稿が見つかりません。' });
  const body = String(req.body.body || '');
  const error = validateText(body, 64, '返信');
  if (error) return res.status(400).json({ error });
  await pool.query('INSERT INTO replies (post_id, user_id, body) VALUES ($1, $2, $3)', [postId, user.id, body]);
  res.status(201).json({ posts: await getFeed() });
}));

app.post('/api/account/register', asyncRoute(async (req, res) => {
  const accountId = normalizeAccountId(req.body.accountId);
  const accountName = String(req.body.accountName || '').trim();
  const password = String(req.body.password || '');
  const error = validateRegistration(accountId, accountName, password);
  if (error) return res.status(400).json({ error });
  const passwordHash = await bcrypt.hash(password, 12);
  let user;
  try {
    const { rows } = await pool.query(`
      INSERT INTO users (account_id, account_name, password_hash)
      VALUES ($1, $2, $3) RETURNING *
    `, [accountId, accountName, passwordHash]);
    user = rows[0];
  } catch (insertError) {
    if (insertError.code === '23505') return res.status(409).json({ error: 'このアカウントIDは既に使われています。' });
    throw insertError;
  }
  req.session.regenerate(err => {
    if (err) return res.status(500).json({ error: 'セッションの作成に失敗しました。' });
    req.session.userId = String(user.id);
    req.session.csrfToken = crypto.randomBytes(32).toString('hex');
    req.session.save(saveError => {
      if (saveError) return res.status(500).json({ error: 'セッションを保存できませんでした。' });
      res.status(201).json({ user: publicUser(user), csrfToken: req.session.csrfToken });
    });
  });
}));

app.post('/api/account/login', asyncRoute(async (req, res) => {
  const accountId = normalizeAccountId(req.body.accountId);
  const password = String(req.body.password || '');
  const { rows } = await pool.query('SELECT * FROM users WHERE LOWER(account_id) = $1 ORDER BY id LIMIT 1', [accountId]);
  const user = rows[0];
  const valid = user ? await bcrypt.compare(password, user.password_hash) : false;
  if (!valid) return res.status(401).json({ error: 'アカウントIDまたはパスワードが正しくありません。' });
  req.session.regenerate(err => {
    if (err) return res.status(500).json({ error: 'ログインできませんでした。' });
    req.session.userId = String(user.id);
    req.session.csrfToken = crypto.randomBytes(32).toString('hex');
    req.session.save(saveError => {
      if (saveError) return res.status(500).json({ error: 'セッションを保存できませんでした。' });
      res.json({ user: publicUser(user), csrfToken: req.session.csrfToken });
    });
  });
}));

app.post('/api/account/logout', (req, res) => {
  req.session.destroy(err => {
    if (err) return res.status(500).json({ error: 'ログアウトできませんでした。' });
    res.clearCookie('dearthsocial.sid');
    res.json({ ok: true });
  });
});

app.patch('/api/account/password', asyncRoute(async (req, res) => {
  const user = await getSessionUser(req);
  if (!user) return res.status(401).json({ error: 'ログインが必要です。' });
  const currentPassword = String(req.body.currentPassword || '');
  const newPassword = String(req.body.newPassword || '');
  const confirmedPassword = String(req.body.confirmPassword || '');
  if (!(await bcrypt.compare(currentPassword, user.password_hash))) return res.status(401).json({ error: '現在のパスワードが正しくありません。' });
  if (newPassword !== confirmedPassword) return res.status(400).json({ error: '新しいパスワードと確認用パスワードが一致しません。' });
  if (newPassword.length < 2 || newPassword.length > 72) return res.status(400).json({ error: 'パスワードは2～72文字で入力してください。' });
  if (await bcrypt.compare(newPassword, user.password_hash)) return res.status(400).json({ error: '現在と異なるパスワードを入力してください。' });
  const passwordHash = await bcrypt.hash(newPassword, 12);
  await pool.query('UPDATE users SET password_hash = $1, updated_at = NOW() WHERE id = $2', [passwordHash, user.id]);
  req.session.destroy(err => {
    if (err) return res.status(500).json({ error: 'パスワードは変更されましたが、セッションの更新に失敗しました。' });
    res.clearCookie('dearthsocial.sid');
    res.json({ ok: true });
  });
}));

app.delete('/api/account', asyncRoute(async (req, res) => {
  const submittedAccountId = normalizeAccountId(req.body.accountId);
  let user = await getSessionUser(req);
  if (!user && submittedAccountId) {
    const { rows } = await pool.query('SELECT * FROM users WHERE LOWER(account_id) = $1 ORDER BY id LIMIT 1', [submittedAccountId]);
    user = rows[0];
  }
  if (!user) return res.status(401).json({ error: 'ログイン情報を確認できません。再ログインするか、アカウントIDとパスワードを入力してください。' });
  if (submittedAccountId && normalizeAccountId(user.account_id) !== submittedAccountId) return res.status(403).json({ error: 'ログイン中のアカウントと入力されたIDが一致しません。' });
  const password = String(req.body.password || '');
  if (!(await bcrypt.compare(password, user.password_hash))) return res.status(401).json({ error: 'パスワードが正しくありません。' });
  await pool.query('DELETE FROM users WHERE id = $1', [user.id]);
  req.session.destroy(err => {
    if (err) return res.status(500).json({ error: 'アカウントは削除しましたが、セッションの削除に失敗しました。' });
    res.clearCookie('dearthsocial.sid');
    res.json({ ok: true });
  });
}));

